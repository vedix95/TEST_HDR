std::string default_icc_directory() {
    const char* xdg = std::getenv("XDG_DATA_HOME");
    if (xdg && xdg[0] != '\0') {
        return std::string(xdg) + "/icc";
    }
    const char* home = std::getenv("HOME");
    if (home && home[0] != '\0') {
        return std::string(home) + "/.local/share/icc";
    }
    return "/tmp/icc";
}

std::string build_aggregated_screen_prefix(const EdidHdrSpecs& edid,
                                           const std::string& connector_override,
                                           const std::string& description_override) {
    std::string conn = !connector_override.empty()
        ? connector_override
        : (!edid.connector.empty() ? edid.connector : "display");
    std::string conn_tok = sanitize_token(conn, true);

    std::string raw_screen = description_override;
    if (raw_screen.empty()) raw_screen = edid.monitor_name;
    if (raw_screen.empty() && !edid.manufacturer_pnp.empty()) {
        raw_screen = edid.manufacturer_pnp;
        if (!edid.product_code_hex.empty()) {
            raw_screen += "_" + edid.product_code_hex;
        }
    }
    std::string screen_tok = sanitize_token(raw_screen, false);
    if (screen_tok.empty()) {
        return conn_tok.empty() ? "display" : conn_tok;
    }
    if (conn_tok.empty()) {
        return screen_tok;
    }
    return screen_tok + "-" + conn_tok;
}

GeneratedIccSet generate_calibrated_icc_profiles(const EdidHdrSpecs& edid,
                                                 const std::string& connector_override,
                                                 const std::string& target_dir,
                                                 const std::string& description_override) {
    namespace fs = std::filesystem;
    GeneratedIccSet res;

    std::string dir_str = target_dir.empty() ? default_icc_directory() : target_dir;
    std::error_code ec;
    fs::create_directories(dir_str, ec);
    if (ec) {
        res.error_msg = "Impossible de créer le dossier ICC : " + dir_str;
        return res;
    }

    std::string conn = !connector_override.empty()
        ? connector_override
        : (!edid.connector.empty() ? edid.connector : "display");
    std::string prefix = build_aggregated_screen_prefix(edid, conn, description_override);
    res.screen_prefix = prefix;

    std::string display_label = !description_override.empty()
        ? description_override
        : (!edid.monitor_name.empty() ? edid.monitor_name : (edid.manufacturer_pnp + " " + edid.product_code_hex));
    if (trim_copy(display_label).empty()) display_label = conn;
    std::string full_label = display_label + " (" + conn + ")";

    // Clean up older non-screen-prefixed files from earlier versions
    cleanup_legacy_icc_files(dir_str, conn);

    fs::path native_path = fs::path(dir_str) / (prefix + "-EDID-Native.icc");
    fs::path p3_path = fs::path(dir_str) / (prefix + "-DCI-P3-D65.icc");
    fs::path srgb_path = fs::path(dir_str) / (prefix + "-sRGB-Calibrated.icc");
    fs::path bt2020_lin_path = fs::path(dir_str) / (prefix + "-BT2020-Linear.icc");
    fs::path bt2020_pq_path = fs::path(dir_str) / (prefix + "-BT2020-PQ.icc");

    double sdr_lumi = 80.0;
    double native_lumi = (edid.has_max && edid.max_nits > 80.0) ? std::round(edid.max_nits) : 250.0;

    // 1. EDID Native Profile
    cmsCIExyY edid_white = {
        edid.has_chromaticity ? edid.white_x : 0.3127,
        edid.has_chromaticity ? edid.white_y : 0.3290,
        1.0,
    };
    cmsCIExyYTRIPLE edid_prim = {
        {edid.has_chromaticity ? edid.red_x : 0.640, edid.has_chromaticity ? edid.red_y : 0.330, 1.0},
        {edid.has_chromaticity ? edid.green_x : 0.300, edid.has_chromaticity ? edid.green_y : 0.600, 1.0},
        {edid.has_chromaticity ? edid.blue_x : 0.150, edid.has_chromaticity ? edid.blue_y : 0.060, 1.0},
    };
    double edid_gamma = (edid.gamma >= 1.0 && edid.gamma <= 3.5) ? edid.gamma : 2.2;
    cmsToneCurve* trc_native = cmsBuildGamma(nullptr, edid_gamma);
    bool ok1 = write_rgb_icc(
        native_path.string(), edid_white, edid_prim, trc_native, native_lumi,
        "[10 BIT SDR] " + full_label + " ICC EDID Natif", display_label);
    if (trc_native) cmsFreeToneCurve(trc_native);

    // 2. Display P3 D65 (sRGB TRC)
    cmsCIExyY d65_white = {0.3127, 0.3290, 1.0};
    cmsCIExyYTRIPLE p3_prim = {
        {0.680, 0.320, 1.0},
        {0.265, 0.690, 1.0},
        {0.150, 0.060, 1.0},
    };
    cmsToneCurve* trc_srgb = make_srgb_trc();
    bool ok2 = write_rgb_icc(
        p3_path.string(), d65_white, p3_prim, trc_srgb, sdr_lumi,
        "[10 BIT SDR] " + full_label + " ICC DCI-P3 D65", display_label);

    // 3. sRGB Calibrated (Rec.709 primaries + sRGB TRC)
    cmsCIExyYTRIPLE srgb_prim = {
        {0.640, 0.330, 1.0},
        {0.300, 0.600, 1.0},
        {0.150, 0.060, 1.0},
    };
    bool ok3 = write_rgb_icc(
        srgb_path.string(), d65_white, srgb_prim, trc_srgb, sdr_lumi,
        "[8 BIT SDR] " + full_label + " ICC sRGB Calibre", display_label);
    if (trc_srgb) cmsFreeToneCurve(trc_srgb);

    // 4. BT.2020 Linear (creative / Darktable / Blender / HDR compositing)
    cmsCIExyYTRIPLE bt2020_prim = {
        {0.708, 0.292, 1.0},
        {0.170, 0.797, 1.0},
        {0.131, 0.046, 1.0},
    };
    cmsToneCurve* trc_linear = cmsBuildGamma(nullptr, 1.0);
    bool ok4 = write_rgb_icc(
        bt2020_lin_path.string(), d65_white, bt2020_prim, trc_linear, native_lumi,
        "[10 BIT HDR] " + full_label + " BT.2020 Lineaire", display_label);
    if (trc_linear) cmsFreeToneCurve(trc_linear);

    // 5. BT.2020 ST.2084 PQ
    cmsToneCurve* trc_pq = make_pq_eotf_trc();
    char pq_desc[256];
    std::snprintf(pq_desc, sizeof(pq_desc), "[10 BIT HDR] %s BT.2020 PQ (%.0f nits)",
                  full_label.c_str(), native_lumi);
    bool ok5 = write_rgb_icc(
        bt2020_pq_path.string(), d65_white, bt2020_prim, trc_pq, native_lumi,
        pq_desc, display_label);
    if (trc_pq) cmsFreeToneCurve(trc_pq);

    if (!ok1 || !ok2 || !ok3 || !ok4 || !ok5) {
        res.error_msg = "Échec lors de l'écriture d'un fichier ICC via lcms2";
        return res;
    }

    res.ok = true;
    res.native_icc_path = native_path.string();
    res.p3_icc_path = p3_path.string();
    res.srgb_icc_path = srgb_path.string();
    res.bt2020_linear_icc_path = bt2020_lin_path.string();
    res.bt2020_pq_icc_path = bt2020_pq_path.string();
    return res;
}

std::string detect_active_hypr_icc(const std::string& connector) {
    std::string hdir = config_hypr_dir();
    if (hdir.empty()) return "";

    {
        std::ifstream ifs(hdir + "/monitors.conf");
        if (ifs) {
            std::string line, cur_out, cur_icc;
            bool in_block = false;
            while (std::getline(ifs, line)) {
                std::string t = trim_copy(line);
                if (t.rfind("monitorv2", 0) == 0) {
                    in_block = true;
                    cur_out.clear();
                    cur_icc.clear();
                    continue;
                }
                if (!in_block) continue;
                if (t == "}") {
                    if (!cur_icc.empty() &&
                        (connector.empty() || cur_out == connector || cur_out.rfind("desc:", 0) == 0)) {
                        return cur_icc;
                    }
                    in_block = false;
                    continue;
                }
                auto eq = t.find('=');
                if (eq != std::string::npos) {
                    std::string k = trim_copy(t.substr(0, eq));
                    std::string v = trim_copy(t.substr(eq + 1));
                    if (k == "output") cur_out = v;
                    else if (k == "icc") cur_icc = v;
                }
            }
        }
    }

    {
        std::ifstream ifs(hdir + "/monitors.lua");
        if (ifs) {
            std::string content((std::istreambuf_iterator<char>(ifs)), std::istreambuf_iterator<char>());
            std::regex mon_re(R"(hl\.monitor\s*\(\s*\{([^}]*)\}\s*\))");
            std::regex out_re("output\\s*=\\s*\"([^\"]*)\"");
            std::regex icc_re("icc\\s*=\\s*\"([^\"]*)\"");
            for (std::sregex_iterator it(content.begin(), content.end(), mon_re), end; it != end; ++it) {
                std::string body = (*it)[1].str();
                std::smatch om, im;
                if (std::regex_search(body, im, icc_re) && !im[1].str().empty()) {
                    if (connector.empty() ||
                        (std::regex_search(body, om, out_re) &&
                         (om[1].str() == connector || om[1].str().rfind("desc:", 0) == 0))) {
                        return im[1].str();
                    }
                }
            }
        }
    }
    return "";
}

static void sync_icc_copies_to_dir(const std::filesystem::path& dest_dir,
                            const std::vector<std::string>& icc_paths) {
    namespace fs = std::filesystem;
    std::error_code ec;
    fs::create_directories(dest_dir, ec);
    if (ec) return;
    for (const std::string& p : icc_paths) {
        fs::path src(p);
        fs::path dst = dest_dir / src.filename();
        fs::copy_file(src, dst, fs::copy_options::overwrite_existing, ec);
    }
}

bool ensure_startup_symlinks(const EdidHdrSpecs& edid,
                             const std::string& connector_override,
                             const std::string& description_override,
                             const std::string& icc_dir_override,
                             const std::string& legacy_icc_dir_override,
                             const std::string& bin_dir_override,
                             const std::string& exe_path_override) {
    namespace fs = std::filesystem;

    std::string icc_dir = icc_dir_override.empty() ? default_icc_directory() : icc_dir_override;
    GeneratedIccSet icc = generate_calibrated_icc_profiles(edid, connector_override, icc_dir, description_override);
    if (!icc.ok) {
        return false;
    }

    const std::vector<std::string> all_icc = {
        icc.native_icc_path,
        icc.p3_icc_path,
        icc.srgb_icc_path,
        icc.bt2020_linear_icc_path,
        icc.bt2020_pq_icc_path,
    };

    const char* home = std::getenv("HOME");
    std::string legacy_dir = legacy_icc_dir_override;
    if (legacy_dir.empty() && home && home[0] != '\0') {
        legacy_dir = std::string(home) + "/.color/icc";
    }
    if (!legacy_dir.empty()) {
        std::error_code ec;
        fs::create_directories(legacy_dir, ec);
        if (!ec) {
            cleanup_broken_symlinks(legacy_dir);
            for (const std::string& p : all_icc) {
                fs::path target(p);
                update_symlink(target, fs::path(legacy_dir) / target.filename());
            }
        }
    }

    // Install real file copies into standard app ICC directories (Krita, Darktable, XDG color/icc)
    if (icc_dir_override.empty() && legacy_icc_dir_override.empty()) {
        const char* xdg_data = std::getenv("XDG_DATA_HOME");
        std::string data_dir = (xdg_data && xdg_data[0] != '\0')
            ? std::string(xdg_data)
            : (home && home[0] != '\0' ? std::string(home) + "/.local/share" : "");
        if (!data_dir.empty()) {
            sync_icc_copies_to_dir(fs::path(data_dir) / "color" / "icc", all_icc);
            sync_icc_copies_to_dir(fs::path(data_dir) / "krita" / "profiles", all_icc);
        }

        const char* xdg_cfg = std::getenv("XDG_CONFIG_HOME");
        std::string cfg_dir = (xdg_cfg && xdg_cfg[0] != '\0')
            ? std::string(xdg_cfg)
            : (home && home[0] != '\0' ? std::string(home) + "/.config" : "");
        if (!cfg_dir.empty()) {
            sync_icc_copies_to_dir(fs::path(cfg_dir) / "darktable" / "color" / "out", all_icc);
        }
    }

    std::string bin_dir = bin_dir_override;
    if (bin_dir.empty() && home && home[0] != '\0') {
        bin_dir = std::string(home) + "/.local/bin";
    }

    fs::path exe_path = exe_path_override;
    if (exe_path.empty()) {
        char exe_buf[4096];
        ssize_t len = readlink("/proc/self/exe", exe_buf, sizeof(exe_buf) - 1);
        if (len > 0) {
            exe_buf[len] = '\0';
            exe_path = exe_buf;
        }
    }

    if (!bin_dir.empty() && !exe_path.empty() && exe_path.filename() == "testhdr") {
        std::error_code ec;
        fs::create_directories(bin_dir, ec);
        if (!ec) {
            update_symlink(exe_path, fs::path(bin_dir) / "testhdr");
        }
    }

    return true;
}

