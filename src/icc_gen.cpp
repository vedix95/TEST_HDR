std::string sanitize_token(const std::string& s, bool allow_dash) {
    std::string out;
    out.reserve(s.size());
    bool last_sep = false;
    for (char c : s) {
        bool is_alnum = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9');
        if (is_alnum || (allow_dash && c == '-')) {
            out.push_back(c);
            last_sep = false;
        } else if (!out.empty() && !last_sep) {
            out.push_back('_');
            last_sep = true;
        }
    }
    while (!out.empty() && (out.back() == '_' || out.back() == '-')) {
        out.pop_back();
    }
    return out;
}

void set_mlu_tag(cmsHPROFILE h, cmsTagSignature sig, const std::string& text) {
    cmsMLU* mlu = cmsMLUalloc(nullptr, 1);
    if (!mlu) return;
    cmsMLUsetASCII(mlu, "en", "US", text.c_str());
    cmsWriteTag(h, sig, mlu);
    cmsMLUfree(mlu);
}

cmsToneCurve* make_srgb_trc() {
    const cmsFloat64Number params[5] = {
        2.4,
        1.0 / 1.055,
        0.055 / 1.055,
        1.0 / 12.92,
        0.04045,
    };
    return cmsBuildParametricToneCurve(nullptr, 4, params);
}

cmsToneCurve* make_pq_eotf_trc() {
    constexpr int kEntries = 1024;
    std::vector<cmsUInt16Number> table(kEntries);
    for (int i = 0; i < kEntries; ++i) {
        double pq = static_cast<double>(i) / static_cast<double>(kEntries - 1);
        double linear = std::clamp(pq_to_nits(pq) / kPqMaxNits, 0.0, 1.0);
        table[i] = static_cast<cmsUInt16Number>(std::llround(linear * 65535.0));
    }
    return cmsBuildTabulatedToneCurve16(nullptr, kEntries, table.data());
}

bool write_rgb_icc(const std::string& path,
                   const cmsCIExyY& white,
                   const cmsCIExyYTRIPLE& primaries,
                   cmsToneCurve* trc,
                   double peak_nits,
                   const std::string& desc,
                   const std::string& model_name) {
    if (!trc) return false;
    cmsToneCurve* curves[3] = {trc, trc, trc};
    cmsHPROFILE h = cmsCreateRGBProfile(&white, &primaries, curves);
    if (!h) return false;

    cmsSetDeviceClass(h, cmsSigDisplayClass);
    cmsSetColorSpace(h, cmsSigRgbData);
    cmsSetPCS(h, cmsSigXYZData);
    cmsSetProfileVersion(h, 4.3);

    set_mlu_tag(h, cmsSigProfileDescriptionTag, desc);
    set_mlu_tag(h, cmsSigDeviceMfgDescTag, "testhdr");
    set_mlu_tag(h, cmsSigDeviceModelDescTag, model_name);
    set_mlu_tag(h, cmsSigCopyrightTag, "Generated by testhdr (lcms2)");

    if (peak_nits > 0.0) {
        cmsCIEXYZ lumi = {0.0, peak_nits, 0.0};
        cmsWriteTag(h, cmsSigLuminanceTag, &lumi);
    }

    cmsBool ok = cmsSaveProfileToFile(h, path.c_str());
    cmsCloseProfile(h);
    return ok != 0;
}

std::string config_hypr_dir() {
    const char* xdg = std::getenv("XDG_CONFIG_HOME");
    if (xdg && xdg[0] != '\0') {
        return std::string(xdg) + "/hypr";
    }
    const char* home = std::getenv("HOME");
    if (home && home[0] != '\0') {
        return std::string(home) + "/.config/hypr";
    }
    return "";
}

std::string trim_copy(const std::string& s) {
    size_t a = 0;
    while (a < s.size() && (s[a] == ' ' || s[a] == '\t' || s[a] == '\r' || s[a] == '\n')) ++a;
    size_t b = s.size();
    while (b > a && (s[b - 1] == ' ' || s[b - 1] == '\t' || s[b - 1] == '\r' || s[b - 1] == '\n')) --b;
    return s.substr(a, b - a);
}

bool update_symlink(const std::filesystem::path& target, const std::filesystem::path& link_path) {
    namespace fs = std::filesystem;
    std::error_code ec;
    fs::file_status st = fs::symlink_status(link_path, ec);
    if (!ec && fs::exists(st)) {
        if (fs::is_symlink(st)) {
            fs::path cur_target = fs::read_symlink(link_path, ec);
            if (!ec && cur_target == target) {
                return true;
            }
            fs::remove(link_path, ec);
            if (ec) return false;
        } else {
            return false;
        }
    } else if (fs::is_symlink(st)) {
        fs::remove(link_path, ec);
    }
    fs::create_symlink(target, link_path, ec);
    return !ec;
}

void cleanup_legacy_icc_files(const std::filesystem::path& icc_dir, const std::string& conn) {
    namespace fs = std::filesystem;
    std::string conn_tok = sanitize_token(conn, true);
    if (conn_tok.empty()) return;
    std::error_code ec;
    for (const char* suffix : {"-EDID-Native.icc", "-DCI-P3-D65.icc", "-sRGB-Calibrated.icc"}) {
        fs::path old_file = icc_dir / (conn_tok + suffix);
        if (fs::exists(old_file, ec)) {
            fs::remove(old_file, ec);
        }
    }
}

void cleanup_broken_symlinks(const std::filesystem::path& dir) {
    namespace fs = std::filesystem;
    std::error_code ec;
    if (!fs::exists(dir, ec)) return;
    for (const auto& entry : fs::directory_iterator(dir, ec)) {
        fs::file_status st = entry.symlink_status(ec);
        if (!ec && fs::is_symlink(st) && !fs::exists(entry.path(), ec)) {
            fs::remove(entry.path(), ec);
        }
    }
}

